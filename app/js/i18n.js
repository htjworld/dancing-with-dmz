// 한 줄 응답(state.note)의 문구. say 가 있으면 지금 언어로 다시 만든다(언어를 바꿔도 응답이 따라 바뀐다)
export const noteText = note => note?.say?.() ?? note?.text ?? '';

// 날짜 표기: 한국어 '7월 26일', 영어 'July 26'
export function dateText(iso) {
  if (!iso) return '';
  const m = +iso.slice(5, 7), d = +iso.slice(8, 10);
  return state.lang === 'en' ? `${['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'][m - 1]}\u00a0${d}` : `${m}월\u00a0${d}일`;
}

export function t(key, vars = {}) {
  const text = TEXT[state.lang]?.[key] ?? TEXT.ko[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
